async def settlement_loop(executor: PolyExecutor, tg: TelegramAlerts, quality_model: QualityModel, bias_tracker: BiasTracker, autocorr: "AutocorrTracker"):























    """Check and settle expired positions every 60 seconds. Sends Telegram on each outcome."""























    while not _shutdown.is_set():























        try:























            # open_positions() returns a list[Position]























            open_before = {pos.id for pos in executor.open_positions()}























            await executor.check_and_settle_expired()























            open_after  = {pos.id for pos in executor.open_positions()}















































            settled_ids = open_before - open_after























            if settled_ids:























                closed_map = {pos.id: pos for pos in executor.closed_positions()}























                for pos_id in settled_ids:























                    pos = closed_map.get(pos_id)























                    if pos is None:























                        continue























                    won      = getattr(pos, "status", "") == "won"























                    sym_part = getattr(pos, 'symbol', '').split('-')[0].lower()























                    dir_part = getattr(pos, 'direction', '').lower()























                    if sym_part and dir_part:























                        quality_model.record(f"{sym_part}_{dir_part}", won)























                        bias_tracker.record(sym_part.upper(), getattr(pos, "direction", ""), won)























                        autocorr.record(sym_part.upper(), getattr(pos, "direction", ""), won)























                    pnl      = getattr(pos, "realized_pnl", 0.0) or 0.0























                    ep       = getattr(pos, "entry_price", 0.0)























                    xp       = getattr(pos, "exit_price", 0.0)























                    icon     = "✅" if won else "❌"























                    outcome  = "WON" if won else "LOST"























                    pnl_str  = f"+${pnl:.2f}" if pnl >= 0 else f"-${abs(pnl):.2f}"























                    symbol    = getattr(pos, "symbol", "")























                    direction = getattr(pos, "direction", "")























                    s = executor.summary()























                    bal_after_d  = s["bankroll"]























                    bal_before_d = round(bal_after_d - pnl, 2)























                    msg = (























                        "[" + BOT_LABEL + "] " + icon + " " + symbol + " " + direction























                        + " " + outcome + " " + pnl_str























                        + " (" + f"{ep:.3f}" + "\u2192" + f"{xp:.3f}" + ")"























                        + "\nBankroll: $" + f"{bal_before_d:.2f}" + "\u2192$" + f"{bal_after_d:.2f}"























                        + "\nSession: W" + str(s['won']) + "/L" + str(s['lost'])























                        + " " + str(s['win_rate']) + "% PnL=$" + f"{s['total_pnl']:+.2f}"























                    )























                    logger.info(f"Settled: {msg}")























                    await _telegram(tg, msg)























        except Exception as e:























            logger.error(f"Settlement error: {e}", exc_info=True)























        try:























            await asyncio.wait_for(_shutdown.wait(), timeout=10)























        except asyncio.TimeoutError:























            pass







































































