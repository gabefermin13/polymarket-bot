# ── Regime gate (S8) ─────────────────────────────────────────────────────────























_regime_cache: dict = {"val": "init", "ts": 0.0}







































































async def _get_regime(client) -> str | None:























    """























    BTC 4h price change via Coinbase 1h candles.























    Returns "Up", "Down", or None (ranging/unknown). Cached REGIME_TTL seconds.























    """























    global _regime_cache























    if _regime_cache["val"] != "init" and time.time() - _regime_cache["ts"] < REGIME_TTL:























        return _regime_cache["val"]























    try:























        now       = int(time.time())























        start_iso = datetime.fromtimestamp(now - 5 * 3600, tz=timezone.utc).isoformat()























        end_iso   = datetime.fromtimestamp(now, tz=timezone.utc).isoformat()























        r = await client.get(























            "https://api.exchange.coinbase.com/products/BTC-USD/candles",























            params={"granularity": 3600, "start": start_iso, "end": end_iso},























            timeout=15.0,























        )























        data = r.json()























        if not data or not isinstance(data, list) or len(data) < 2:























            raise ValueError("insufficient candle data")























        # [timestamp, low, high, open, close, volume] — newest first























        current_price = float(data[0][4])























        old_price     = float(data[-1][4])























        pct           = (current_price - old_price) / old_price























        DEADBAND      = 0.015  # 1.5% — within this = ranging























        if pct < -DEADBAND:























            regime = "Down"























        elif pct > DEADBAND:























            regime = "Up"























        else:























            regime = None























        logger.info(























            f"[Regime] BTC 4h: {pct:+.2%} "























            f"(${old_price:,.0f}→${current_price:,.0f}) → {regime or 'Ranging'}"























        )























        _regime_cache = {"val": regime, "ts": time.time()}























        return regime























    except Exception as e:























        logger.warning(f"[Regime] fetch failed: {e} — no gate applied")























        _regime_cache = {"val": None, "ts": time.time()}























        return None







































































