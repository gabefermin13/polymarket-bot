def _fmt_duration(secs: float) -> str:























    """Format seconds into a compact human-readable string: 4m30s, 12m, 1h2m."""























    secs = int(secs)























    if secs >= 3600:























        return f"{secs // 3600}h{(secs % 3600) // 60}m"























    elif secs >= 60:























        mins = secs // 60























        rem  = secs % 60























        return f"{mins}m{rem}s" if rem else f"{mins}m"























    return f"{secs}s"







































































def _pick_market(markets: list[dict], direction: str) -> dict | None:























    """























    From a list of active markets (MarketFinder.get_active_markets),























    pick the soonest-expiring one that isn't already entered and has























    enough time left.  All markets contain both up_token_id/down_token_id.























    """























    now = time.time()























    for m in markets:   # already sorted ascending by end_time























        if m["end_time"] - now < MIN_SECS_LEFT:























            continue























        cond_key = f"{m['condition_id']}-{direction}"























        if cond_key in _entered:























            continue























        return m























    return None







































































# ── Signal scan ───────────────────────────────────────────────────────────────















































async def _scan_once(























    client: httpx.AsyncClient,























    executor: PolyExecutor,























    mf: MarketFinder,























    dc: DirectionConsensus,























    tg: TelegramAlerts,























    quality_model: QualityModel,























    chop_gate: ChoppinessGate,























    bias_tracker: BiasTracker,























    autocorr: "AutocorrTracker",























    econ_cal: EconCalendar,























):























    now_ms = int(time.time() * 1000)























    # Economic calendar blackout — skip entire scan cycle if macro release imminent











    if await econ_cal.is_blackout(client):











        logger.info("EconCalendar blackout active — skipping scan cycle")











        return























    for asset in ASSETS:























        try:























            # Dead zone — formerly hard-skipped; now ML decides (Step 2)























            # Pass 1 — evaluate S1-S5 + S7 (S6 skipped; no token_id yet)























            r1 = await dc.evaluate(client, asset, token_id="", ts_ms=now_ms)















































            if r1.direction is None or r1.n_signals < CONSENSUS_REQUIRED:























                logger.debug(f"{asset}: {r1.n_signals} signals ({r1.direction}) — below threshold")























                continue















































            direction    = r1.direction          # "UP" or "DOWN"























            direction_pm = "Up" if direction == "UP" else "Down"















































            # Find active markets for this asset + direction























            markets = mf.get_active_markets(























                symbol=f"{asset}-USD",























                min_seconds_remaining=MIN_SECS_LEFT,























                min_liquidity=MIN_LIQUIDITY_USD,























            )























            if not markets:























                logger.debug(f"{asset}: no active {direction_pm} markets with liquidity >= ${MIN_LIQUIDITY_USD:.0f}")























                continue















































            market = _pick_market(markets, direction_pm)























            if market is None:























                logger.debug(f"{asset} {direction_pm}: all markets already entered or expiring")























                continue















































            token_id = (market["up_token_id"]























                        if direction == "UP"























                        else market["down_token_id"])















































            # Pass 2 — re-evaluate with real token_id (S6 now live; everything else cached)























            r2 = await dc.evaluate(client, asset, token_id=token_id, ts_ms=now_ms)















































            # Weighted signal count.  S2 is contrarian (IC<0): agreement hurts,











            # disagreement helps.  S3 upweighted (IC>0).  Others count as 1.











            n_for_dir = 0.0











            for sig_name, sig_info in r2.signal_details.items():











                sig_dir = sig_info.get("direction", "")











                if sig_dir in _NON_DIR:











                    continue











                w = SIGNAL_WEIGHTS.get(sig_name, 1.0)











                if sig_dir == direction:











                    n_for_dir += w          # agreement: +w (negative w hurts)











                elif w < 0:











                    n_for_dir += abs(w)     # contrarian disagreement: positive evidence















































            # Regime bias — adjust confidence based on macro trend alignment























            regime = await _get_regime(client)























            if regime is not None and direction_pm == regime:























                adj_conf = min(r2.conf + REGIME_BOOST, 0.95)























            elif regime is not None and direction_pm != regime:























                adj_conf = max(r2.conf - REGIME_PENALTY, 0.50)























            else:























                adj_conf = r2.conf  # ranging — no adjustment























            # Autocorrelation adjustment — recent streak boosts/fades confidence











            autocorr_adj = autocorr.get_conf_adj(asset, direction_pm)











            adj_conf     = max(0.50, min(0.95, adj_conf + autocorr_adj))























            logger.info(























                f"{asset} {direction_pm}: regime={regime or 'Ranging'} "























                f"autocorr={autocorr_adj:+.3f} "























                f"n={n_for_dir} conf {r2.conf:.3f}→{adj_conf:.3f}"























            )
            # signal breakdown injected
            _sd = r2.signal_details
            _sb = ' '.join(
                f"{k}={'D' if v.get('direction')=='DOWN' else 'U' if v.get('direction')=='UP' else '~' if v.get('direction') in ('NEUTRAL','FLAT','BALANCED') else '-'}"
                for k, v in sorted(_sd.items())
            )
            logger.info(f"{asset} {direction_pm}: sigs [{_sb}]")
















































            secs_left = market["end_time"] - time.time()
            # Skip markets with too much time remaining (long entries 39% WR)
            _MAX_SECS = int(os.getenv("MAX_MARKET_SECS_LEFT", "900"))
            if secs_left > _MAX_SECS:
                logger.debug(f"{asset}: secs_left={secs_left:.0f} > {_MAX_SECS} -- skip")
                continue
























            sig_base  = {























                "ts":           now_ms,























                "asset":        asset,























                "direction":    direction_pm,























                "condition_id": market["condition_id"],























                "token_id":     token_id,























                "symbol":       market["symbol"],























                "secs_left":    round(secs_left, 1),























                "signals":      r2.signal_details,























                "n_signals":    n_for_dir,























                "conf":         adj_conf,























                "bot":          BOT_LABEL,























            }















































            if n_for_dir < CONSENSUS_REQUIRED:























                logger.info(























                    f"{asset}: {n_for_dir} agreeing signals (need {CONSENSUS_REQUIRED}) — skip"























                )























                _log_signal({**sig_base, "executed": False, "skip_reason": "below_threshold_after_s6"})























                continue























            # Time-zone gates











            zone = _trade_zone()























            # Global base confidence floor (raised from 0.55 to 0.65)











            if adj_conf < BASE_MIN_CONF:











                logger.info(











                    f"{asset} {direction_pm}: conf {adj_conf:.3f} below base floor {BASE_MIN_CONF:.2f} — skip"











                )











                _log_signal({**sig_base, "executed": False, "skip_reason": "base_min_conf"})











                continue

            # Per-combo minimum confidence gate (env: {ASSET}_{DIR}_MIN_CONF)
            _combo_floor = _combo_min_conf(asset, direction_pm)
            if _combo_floor > 0.0 and adj_conf < _combo_floor:
                logger.info(
                    f"{asset} {direction_pm}: conf {adj_conf:.3f} below combo floor {_combo_floor:.2f} -- skip"
                )
                _log_signal({**sig_base, "executed": False, "skip_reason": "combo_min_conf"})
                continue

            # Per-asset open-position cap (env: MAX_{ASSET}_POSITIONS, default MAX_ASSET_POSITIONS)
            _asset_cap_default = int(os.getenv("MAX_ASSET_POSITIONS", "3"))
            _asset_cap = int(os.getenv(f"MAX_{asset.upper()}_POSITIONS", str(_asset_cap_default)))
            _asset_open = sum(
                1 for p in executor.open_positions()
                if (p.symbol or "").split("-")[0].upper() == asset.upper()
            )
            if _asset_open >= _asset_cap:
                logger.info(
                    f"{asset} {direction_pm}: {_asset_open} open positions at cap ({_asset_cap}) -- skip"
                )
                _log_signal({**sig_base, "executed": False, "skip_reason": "asset_open_cap"})
                continue
























            # Strict zone hard gates removed (Step 2) — ML decides signal quality























            # Peak zone: boost kelly multiplier (09-10, 14, 18-21 UTC)











            peak_mult = PEAK_KELLY_BOOST if zone == "peak" else 1.0























            # Choppiness gate (global)























            if chop_gate.is_paused():























                logger.info(























                    f"{asset} {direction_pm}: market choppy — skip"























                )























                _log_signal({**sig_base, "executed": False, "skip_reason": "choppy_market"})























                continue















































            # Bias gate (per asset+direction rolling WR circuit breaker)























            if bias_tracker.is_paused(asset, direction_pm):
                logger.info(
                    f"{asset} {direction_pm}: bias paused (low rolling WR) — skip"
                )
                _log_signal({**sig_base, "executed": False, "skip_reason": "bias_paused"})
                continue















































            # Per-combo min_conf gate removed (Step 2) — ML decides























            # Quality gate (per entity)























            entity_key = f"{asset.lower()}_{direction_pm.lower()}"























            kelly_mult = max(quality_model.get_multiplier(entity_key), 0.5)  # Step 2: floor at 0.5x — ML decides















































            # CLOB gate — veto if the market is selling the token we're about to buy























            bid_usd, ask_usd = await polymarket_data.get_orderbook(token_id)


            _clob_ratio = round(ask_usd / bid_usd, 1) if bid_usd > 0 else 0.0


            sig_base["clob_ratio"] = _clob_ratio























            if bid_usd > 0 and ask_usd > 0 and (ask_usd / bid_usd) > CLOB_VETO_RATIO:























                logger.info(























                    f"[CLOB] skip {asset} {direction_pm} — "























                    f"ask/bid={ask_usd/bid_usd:.2f} (ask=${ask_usd:.0f} bid=${bid_usd:.0f})"























                )























                _log_signal({**sig_base, "executed": False, "skip_reason": "clob_imbalance"})























                continue















































            logger.info(























                f"[{BOT_LABEL}] SIGNAL {asset} {direction_pm} | "























                f"n={n_for_dir} conf={adj_conf:.3f} secs_left={secs_left:.0f}"























            )











            # Drift EV gate: enter only when mispricing gives exploitable EV











            _dur = detect_market_duration(market.get("title", ""), secs_left)











            _ev  = await _dev.compute_ev(











                asset, direction_pm, token_id, market["condition_id"],











                market["end_time"], _dur, client,











            )











            # EV -> Kelly multiplier (no longer a hard block)


            _ev_mult = (0.6 if _ev.ev < 0


                        else 0.8 if _ev.ev < 0.04


                        else min(1.2, 1.0 + (_ev.ev - 0.04) * 10))


            logger.info(


                f"{asset} {direction_pm}: EV {_ev.summary()} -> kelly_mult={_ev_mult:.2f}"


            )











            # EV positive: boost confidence proportionally











            adj_conf = min(0.95, adj_conf + _ev.ev * _dev.EV_CONF_BOOST)











            logger.info(











                f"{asset} {direction_pm}: EV gate PASS {_ev.summary()} adj_conf->{adj_conf:.3f}"











            )

            # Price structure rule (Step 2): if YES ask < 0.30, flip to Down
            if direction_pm == "Up" and _ev.ask < 0.30:
                _flip_market = _pick_market(markets, "Down")
                if _flip_market is None:
                    logger.info(
                        f"{asset}: YES ask {_ev.ask:.2f} < 0.30 -- no Down market, skip"
                    )
                    _log_signal({**sig_base, "executed": False, "skip_reason": "yes_below_30c_no_flip"})
                    continue
                logger.info(
                    f"{asset}: YES ask {_ev.ask:.2f} < 0.30 -- flipping Up->Down"
                )
                direction_pm = "Down"
                market      = _flip_market
                token_id    = _flip_market.get("token_id", "") or ""
                sig_base["direction"] = "Down"
                _ev = await _dev.compute_ev(
                    asset, direction_pm, token_id, market["condition_id"],
                    market["end_time"], _dur, client,
                )
                _ev_mult = (0.6 if _ev.ev < 0
                            else 0.8 if _ev.ev < 0.04
                            else min(1.2, 1.0 + (_ev.ev - 0.04) * 10))
                adj_conf = min(0.95, adj_conf + _ev.ev * _dev.EV_CONF_BOOST)
























            # ML gate: calibrated P(win) score, Kelly scaling











            _start_ts = market["end_time"] - _dur











            _ml_score = await _ml.score(











                symbol    = asset,











                direction = direction_pm,











                start_ts  = _start_ts,











                end_ts    = market["end_time"],











                ask_price = _ev.ask,











                extra_features = {











                    "ev":           _ev.ev,











                    "p_win":        _ev.p_win,











                    "drift_pct":    _ev.drift_signed * 100,











                    "drift_signed": _ev.drift_signed,











                },











            )











            _trade_ok, _ml_reason = _ml.should_trade(_ml_score, _ev.ask)











            if not _trade_ok:











                logger.info(f"{asset} {direction_pm}: ML skip — {_ml_reason}")











                _log_signal({**sig_base, "executed": False, "skip_reason": _ml_reason,











                             "ml_pwin": round(_ml_score.p_win, 4),











                             "ml_ev": round(_ml_score.ev, 4)})











                continue











            logger.info(











                f"{asset} {direction_pm}: ML PASS p_win={_ml_score.p_win:.3f} "











                f"kelly_scale={_ml_score.kelly_scale:.2f}x has_model={_ml_score.has_model}"











            )






            # Per-combo ML threshold (env-overridable)
            _combo_ml_env = 'ML_MIN_' + asset.upper() + '_' + direction_pm.upper().replace(' ', '_')
            _combo_ml_min = float(os.getenv(_combo_ml_env, '0.0'))
            if _combo_ml_min > 0 and _ml_score.p_win < _combo_ml_min:
                logger.info(f'{asset} {direction_pm}: combo ML floor {_combo_ml_min:.2f} > p_win={_ml_score.p_win:.3f} -- skip')
                _log_signal({**sig_base, 'executed': False, 'skip_reason': 'combo_ml_min',
                             'ml_pwin': round(_ml_score.p_win, 4)})
                continue

            # Combo-tier Kelly multiplier (Tier 1=1.3x, Tier 2=1.0x, default=0.8x)
            _COMBO_KELLY_TIERS = {
                ('BTC',  'Down'): float(os.getenv('TIER_KELLY_BTC_DOWN',  '1.3')),
                ('XRP',  'Down'): float(os.getenv('TIER_KELLY_XRP_DOWN',  '1.0')),
                ('DOGE', 'Up'):   float(os.getenv('TIER_KELLY_DOGE_UP',   '1.0')),
                ('XRP',  'Up'):   float(os.getenv('TIER_KELLY_XRP_UP',    '1.0')),
            }
            _tier_mult = _COMBO_KELLY_TIERS.get((asset, direction_pm),
                                                float(os.getenv('TIER_KELLY_DEFAULT', '0.8')))

            # Kronos Kelly multiplier -- direction + vol forecast from Frankfurt proxy


            _kronos_mult = await _get_kronos_kelly(asset, direction_pm)





            # Execute via shared PolyExecutor











            pos, skip_reason = await executor.execute(























                market           = market,























                direction        = direction_pm,























                confidence       = adj_conf,























                source           = f"direction:{BOT_LABEL}",























                kelly_multiplier = kelly_mult * peak_mult * _ml_score.kelly_scale * _tier_mult * _kronos_mult * _ev_mult,























            )















































            cond_key = f"{market['condition_id']}-{direction_pm}"















































            if pos is not None:























                _entered.add(cond_key)























                _log_signal({**sig_base, "executed": True,
                             "contracts": pos.contracts, "entry_price": pos.entry_price,
                             "cost_usd": pos.cost_usd, "adj_conf": adj_conf,
                             "regime": regime,
                             "ml_pwin": round(_ml_score.p_win, 4),
                             "ml_kelly": round(_ml_score.kelly_scale, 3)})























                # Build signal tag string (e.g. "S1 S3 S5 S7")











                _NON_DIR_SET = {"NEUTRAL", "NONE", "BALANCED", "FLAT", ""}











                _fired = []











                for _sn, _si in r2.signal_details.items():











                    _sd = _si.get("direction", "")











                    if _sd in _NON_DIR_SET:











                        continue











                    _w = SIGNAL_WEIGHTS.get(_sn, 1.0)











                    if _sd == direction_pm or _w < 0:











                        _fired.append(_sn.upper())











                _sigs_str = " ".join(_fired) if _fired else "—"























                msg = (f"[{BOT_LABEL}] {asset} {direction_pm} | "























                       f"n={n_for_dir:.1f} conf={adj_conf:.3f} zone={zone} "























                       f"@{pos.entry_price:.3f} ${pos.cost_usd:.2f} "























                       f"[{_fmt_duration(secs_left)}]"























                       f"\n{_sigs_str}")























                logger.info(f"Entered: {msg}")























                await _telegram(tg, msg)























            else:























                _log_signal({**sig_base, "executed": False, "skip_reason": "executor_skip"})























                logger.info(f"{asset} {direction_pm}: executor skipped — {skip_reason}")















































        except Exception as e:























            logger.error(f"Error scanning {asset}: {e}", exc_info=True)







































































